const ISOMETRIC = new Set<MovePattern>(['plank', 'side_plank', 'wall_sit', 'superman']);
const EXPLOSIVE = new Set<MovePattern>(['swing', 'clean', 'jacks', 'run']);
const HEAVY = new Set<MovePattern>(['squat', 'hinge', 'bench', 'press', 'leg_press', 'smith_squat', 'lunge']);

export function breathingFor(pattern: MovePattern): string {
  if (ISOMETRIC.has(pattern)) return 'Respire calmement et régulièrement pendant tout le maintien, ventre gainé : ne bloque pas.';
  if (EXPLOSIVE.has(pattern)) return 'Souffle fort au moment de l’effort explosif, inspire pendant le retour.';
  const base = 'Inspire pendant la phase de retour, souffle pendant l’effort.';
  return HEAVY.has(pattern) ? `${base} Sur les séries lourdes : grande inspiration et ventre gainé avant la descente, bloque pendant la répétition, puis souffle en haut.` : base;
}

export function tempoFor(pattern: MovePattern): string {
  if (ISOMETRIC.has(pattern)) return 'Maintien : commence par 20–30 s, ajoute 5–10 s quand c’est facile.';
  if (EXPLOSIVE.has(pattern)) return 'Rapide et explosif, mais toujours contrôlé ; arrête la série dès que la technique se dégrade.';
  return 'Environ 1 s pour l’effort, 2 à 3 s pour le retour, sans rebond. Va jusqu’à 0–3 répétitions de l’échec.';
}

